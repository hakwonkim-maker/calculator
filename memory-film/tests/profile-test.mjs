import { createServer } from 'vite';
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PW_PATH || 'playwright');
const root = path.dirname(fileURLToPath(import.meta.url));
const photos = fs.readdirSync(path.join(root, 'fixtures')).filter((f) => f.endsWith('.jpg')).sort();
const items = photos.map((f, i) => ({ id: 'p' + i, type: 'photo', path: '/@fs' + path.join(root, 'fixtures', f), caption: i === 0 ? '창립 기념식' : '', label: i === 0 ? '1996' : '' }));
const style = process.argv[2] || 'golden';
const server = await createServer({ configFile: path.join(root, '..', 'vite.config.js'), server: { port: 5193 }, logLevel: 'error' });
await server.listen();
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage();
p.on('pageerror', (e) => console.log('[pageerror]', e.message));
await p.goto('http://localhost:5193/harness.html');
await p.waitForFunction(() => window.ready);
const info = await p.evaluate(([pr]) => window.setup(pr, 1280, 720), [{ items, intro: { style }, style: { theme: 'noir' } }]);
const ts = [2, 6, 9, 11, 13, 15.5, 20, info.total - 7, info.total - 3];
const res = await p.evaluate((ts) => window.profile(ts), ts);
console.table(res);
await b.close();
await server.close();
